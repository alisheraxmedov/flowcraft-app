import 'package:flowcraft/theme/flow_theme.dart';

/// Provides default theme instances for FlowCraft.
///
/// Use [FlowTheme.light()] or [FlowTheme.dark()] directly,
/// or create a fully custom [FlowTheme].
class DefaultTheme {
  /// The built-in light theme.
  static FlowTheme light() => FlowTheme.light();

  /// The built-in dark theme.
  static FlowTheme dark() => FlowTheme.dark();
}
